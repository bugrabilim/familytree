export const DICTS: Record<Lang, Dict> = { tr, en };

/** `{name}` biçimli yer tutucuları params ile doldurur. */
function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, key: string) => {
    const v = params[key];
    return v === undefined ? whole : String(v);
  });
}

/**
 * Saf çeviri: geçerli dil sözlüğünde anahtarı arar, `{name}` interpolasyonunu
 * uygular. Çeviri yoksa `tr` karşılığına, o da yoksa anahtarın kendisine düşer —
 * hiçbir zaman `undefined` döndürmez.
 */
export function translate(
  lang: Lang,
  key: string,
  params?: Record<string, string | number>
): string {
  const template = DICTS[lang]?.[key] ?? tr[key] ?? key;
  return interpolate(template, params);
}
